#!/usr/bin/env node
/**
 * Bundles every migration into a single paste-ready file:
 *
 *   supabase/apply-all.sql
 *
 * The Supabase SQL editor accepts one script at a time, so applying ten migrations by hand is
 * tedious and easy to get out of order. This produces exactly the same sequence the CLI would
 * run, guarded so it can only be applied to an empty project.
 *
 *   node scripts/build-apply-all-sql.mjs
 *
 * Excluded on purpose: `supabase/local/00-shim-pre.sql` (that is only for bare PostgreSQL) and
 * `supabase/seed.sql` (demo salon content). Load `supabase/seed-catalog.sql` separately if you
 * want the imported supplier products.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = resolve(ROOT, 'supabase/migrations');
const OUT = resolve(ROOT, 'supabase/apply-all.sql');

const files = readdirSync(MIGRATIONS)
  .filter((name) => name.endsWith('.sql'))
  .sort(); // filenames are timestamp-prefixed, so lexicographic == chronological

if (files.length === 0) {
  console.error('No migrations found in supabase/migrations');
  process.exit(1);
}

const header = `-- ═════════════════════════════════════════════════════════════════════════════
-- Alikati Beauty Home — COMPLETE SCHEMA, single file
--
-- Generated by scripts/build-apply-all-sql.mjs — do not edit by hand.
-- ${files.length} migrations, in order:
${files.map((f, i) => `--   ${String(i + 1).padStart(2)}. ${f}`).join('\n')}
--
-- HOW TO USE
--   1. Supabase dashboard → SQL Editor → New query
--   2. Paste this whole file and Run.
--   3. Then create your admin account:
--        node scripts/create-admin.mjs --email=you@example.com --password='…' --name="…"
--
-- SAFETY
--   • The whole bundle runs inside ONE transaction, so if any statement fails the database
--     is rolled back to its previous state — it can never be left half-migrated.
--   • A guard refuses to start on a project that already has the schema, with a clear message
--     instead of a confusing "type already exists" error.
-- To re-run on an existing project, use the Supabase CLI: supabase db push
-- ═════════════════════════════════════════════════════════════════════════════

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_name = 'salon_settings'
    ) THEN
        RAISE EXCEPTION
            'This database already has the Alikati schema. Nothing was changed. Use the Supabase CLI (supabase db push) to apply new migrations.';
    END IF;
END $$;

BEGIN;

`;

const parts = files.map((name) => {
  const body = readFileSync(join(MIGRATIONS, name), 'utf8');
  return `-- ─────────────────────────────────────────────────────────────────────────────
-- ${name}
-- ─────────────────────────────────────────────────────────────────────────────

${body.trim()}
`;
});

const footer = `
COMMIT;

-- ═════════════════════════════════════════════════════════════════════════════
-- Done. Expected: 14 tables in the public schema, RLS enabled on all of them, and one row
-- in salon_settings. Verify with:
--   select count(*) from information_schema.tables where table_schema = 'public';
--   select count(*) from public.salon_settings;   -- must be 1
-- ═════════════════════════════════════════════════════════════════════════════
`;

const output = header + parts.join('\n') + footer;
writeFileSync(OUT, output, 'utf8');

const kb = (Buffer.byteLength(output) / 1024).toFixed(1);
console.log(`✔ supabase/apply-all.sql — ${files.length} migrations, ${kb} KB`);
